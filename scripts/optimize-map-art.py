"""Export existing map art to sized, content-hashed WebP files (requires Pillow)."""
from pathlib import Path
from io import BytesIO
import hashlib
import json
import re
from PIL import Image, ImageChops, features

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "public/assets/maps/red-banner/modular"
CONFIG = (
    ("ground", "ground-earth-a", "art/ground-materials/v0.1.9.0/earth-a.png", 512, False),
    ("groundVariant", "ground-earth-b", "art/ground-materials/v0.1.9.0/earth-b.png", 512, False),
    ("grass", "ground-grass-a", "art/ground-materials/v0.1.9.0/grass-a.png", 512, False),
    ("grassVariant", "ground-grass-b", "art/ground-materials/v0.1.9.0/grass-b.png", 512, False),
    ("tree", "tree-spruce", "art/map-style-samples/v1/tree-style-v1.png", 768, True),
    ("cliff", "rock-outcrop", "art/terrain-readability/v0.1.5.2/rock-outcrop.png", 768, True),
    ("water", "river-water", "art/terrain-readability/v0.1.5.2/river-water.png", 512, False),
)


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    assets = []
    files = {}
    for kind, name, source_name, max_width, alpha in CONFIG:
        source = ROOT / source_name
        with Image.open(source) as original:
            original.load()
            image = original.convert("RGBA" if alpha else "RGB")
            if image.width > max_width:
                size = (max_width, round(image.height * max_width / image.width))
                image = image.resize(size, Image.Resampling.LANCZOS)
            stream = BytesIO()
            image.save(stream, format="WEBP", quality=88, method=6, exact=True)
            payload = stream.getvalue()
            digest = hashlib.sha256(payload).hexdigest()
            filename = f"{name}.{digest[:12]}.webp"
            with Image.open(BytesIO(payload)) as decoded:
                decoded.load()
                assert decoded.size == image.size
                if alpha:
                    assert decoded.mode == "RGBA"
                    assert decoded.getchannel("A").getextrema() == (0, 255)
                    assert ImageChops.difference(image.getchannel("A"), decoded.getchannel("A")).getbbox() is None
                else:
                    assert decoded.mode == "RGB"
            (OUTPUT / filename).write_bytes(payload)
            files[kind] = "modular/" + filename
            assets.append({
                "asset_id": "modular_" + kind, "filename": filename,
                "source": str(source.relative_to(ROOT)).replace("\\", "/"),
                "source_type": "ai_generated", "generator": "built-in image_gen (original source)",
                "processing": {"encoder": "Pillow / libwebp", "webp_version": features.version("webp"),
                               "quality": 88, "method": 6, "resampling": "LANCZOS"},
                "source_width_px": original.width, "source_height_px": original.height,
                "width_px": image.width, "height_px": image.height, "has_alpha": alpha,
                "alpha_matches_resized_source": True if alpha else None,
                "source_file_bytes": source.stat().st_size,
                "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "file_bytes": len(payload), "sha256": digest,
                "status": "integrated", "visual_approved": False,
            })
    before = sum(asset["source_file_bytes"] for asset in assets)
    after = sum(asset["file_bytes"] for asset in assets)
    assert after <= 1024 * 1024, "Core map assets exceed the 1 MiB budget"
    version = re.search(r'GAME_VERSION = "([^"]+)"', (ROOT / "src/version.ts").read_text(encoding="utf-8")).group(1)
    manifest = {"game_version": version, "source_total_bytes": before,
                "runtime_total_bytes": after, "reduction_percent": round((1 - after/before)*100, 2),
                "assets": assets}
    (OUTPUT / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    registry = "// Generated by scripts/optimize-map-art.py; filenames contain the WebP content hash.\n"
    registry += "export const MAP_ASSET_FILES = " + json.dumps(files, indent=2) + " as const;\n"
    (ROOT / "src/scene/mapAssetFiles.ts").write_text(registry, encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
